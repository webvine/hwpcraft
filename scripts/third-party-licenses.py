def cargo_metadata() -> dict:
    return json.loads(
        subprocess.run(
            ["cargo", "+1.98.1", "metadata", "--format-version", "1", "--offline", "--locked"],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    )


def third_party(meta: dict) -> list[dict]:
    """The packages reachable from the workspace members, members left out."""
    members = set(meta["workspace_members"])
    by_id = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    seen: set[str] = set()
    stack = list(members)
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        stack.extend(dep["pkg"] for dep in nodes[pid]["deps"])
    pkgs = [by_id[pid] for pid in seen if pid not in members]
    return sorted(pkgs, key=lambda p: (p["name"].lower(), p["version"]))


def chosen_license(expr: str) -> tuple[str, list[str]]:
    """The license taken from `expr` and the alternatives not taken, for a plain
    choice ("A OR B", "A/B"); otherwise (`expr`, [])."""
    if "AND" in expr or "WITH" in expr.replace("WITH LLVM-exception", ""):
        return expr, []
    parts = [p.strip() for p in re.split(r"\s+OR\s+|/", expr) if p.strip()]
    if len(parts) < 2:
        return expr, []
    pick = "MIT" if "MIT" in parts else "Apache-2.0" if "Apache-2.0" in parts else parts[0]
    return pick, [p for p in parts if p != pick]


def license_files(pkg: dict) -> list[Path]:
    """The license files of `pkg`: in its folder, or for a crate inside a
    repository checked out next to HwpCraft (RHWP, WordCraft) in the folders
    above it up to that repository's root."""
    folder = Path(pkg["manifest_path"]).parent
    registry = pkg.get("source") is not None
    while True:
        files = sorted(
            (f for f in folder.iterdir() if f.is_file() and LICENSE_FILE.match(f.name)),
            key=lambda f: f.name.lower(),
        )
        if files or registry or (folder / ".git").exists() or folder.parent == folder:
            return files
        folder = folder.parent


def drop_alternatives(files: list[Path], dropped: list[str]) -> list[Path]:
    words = [w for lic in dropped for w in ALTERNATIVE_WORDS.get(lic, ())]
    kept = [f for f in files if not any(w in f.name.lower() for w in words)]
    return kept or files


def read_text(path: Path) -> str:
    text = path.read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n")
    return "\n".join(line.rstrip() for line in text.strip("\n").split("\n"))


def standard_text(pkg: dict, lic: str, shared_apache: str | None) -> str:
    authors = ", ".join(a.split("<")[0].strip() for a in pkg.get("authors") or [])
    holder = authors or f"the {pkg['name']} authors"
    if lic == "MIT" or lic.startswith("MIT AND") or lic.startswith("(MIT"):
        return f"MIT License\n\nCopyright (c) {holder}\n\n{MIT_TEXT}"
    if lic == "BSL-1.0":
        return f"Copyright (c) {holder}\n\n{BSL_TEXT}"
    if lic == "Apache-2.0" and shared_apache:
        return shared_apache
    raise SystemExit(f"{pkg['name']} {pkg['version']}: no license file and no standard text for {lic}")


def build() -> str:
    meta = cargo_metadata()
    pkgs = third_party(meta)
    entries: list[tuple[dict, str, list[tuple[str, str]]]] = []
    missing: list[tuple[dict, str]] = []
    for pkg in pkgs:
        expr = pkg.get("license") or "(see repository)"
        pick, dropped = chosen_license(expr)
        files = drop_alternatives(license_files(pkg), dropped)
        texts = [(f.name, read_text(f)) for f in files]
        entries.append((pkg, pick, texts))
        if all(name.upper().startswith("AUTHORS") for name, _ in texts):
            missing.append((pkg, pick))
    # The Apache-2.0 text most crates ship, for the ones that ship none.
    apache = [t for _, _, ts in entries for n, t in ts if "apache" in n.lower() and "Version 2.0" in t]
    shared_apache = max(set(apache), key=apache.count) if apache else None
    for pkg, pick in missing:
        for entry in entries:
            if entry[0] is pkg:
                entry[2].append(("(standard text)", standard_text(pkg, pick, shared_apache)))
    counts: dict[str, int] = {}
    for _, _, texts in entries:
        for _, t in texts:
            counts[t] = counts.get(t, 0) + 1
    shared = [t for t, c in counts.items() if c > 1]
    shared.sort(key=lambda t: (-counts[t], t))
    labels = {t: f"[T{i + 1}]" for i, t in enumerate(shared)}

    version = (ROOT / "VERSION").read_text(encoding="utf-8").strip()
    out = [
        "HwpCraft third-party licenses",
        "",
        f"The copyright notices and license texts of the {len(entries)} third-party Rust crates",
        f"HwpCraft {version} is built from (THIRD-PARTY-DEPENDENCIES.md), as shipped in each",
        "crate. A crate offered under a choice of licenses is used under MIT where",
        "available, otherwise Apache-2.0. Texts used by several crates are printed once",
        "at the end and referred to as [T1], [T2], ... Fonts, icons and data bundled with",
        "HwpCraft are listed in THIRD-PARTY-NOTICES.txt with their license files.",
        "Generated by scripts/third-party-licenses.py.",
        "",
    ]
    rule = "=" * 78
    for pkg, pick, texts in entries:
        expr = pkg.get("license") or "(see repository)"
        used = f"; used under {pick}" if pick != expr else ""
        out += [rule, f"{pkg['name']} {pkg['version']} ({expr}{used})"]
        if pkg.get("repository"):
            out.append(pkg["repository"])
        out.append(rule)
        for name, text in texts:
            if text in labels:
                out.append(f"{name}: see {labels[text]} below")
            else:
                out += ["", f"--- {name} ---", "", text]
        out.append("")
    out += [rule, "Shared license texts", rule, ""]
    for text in shared:
        out += [f"{labels[text]} ({counts[text]} crates)", "-" * 78, "", text, ""]
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("THIRD-PARTY-LICENSES.txt is out of date; run scripts/third-party-licenses.py")
            return 1
        print("THIRD-PARTY-LICENSES.txt is current")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{OUT.name}: {len(text.encode('utf-8'))} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
